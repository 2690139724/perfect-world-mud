export function findQuest(id: string): IQuest | undefined {
  const q = QUEST_DATA.find(q => q.id === id);
  if (!q) return undefined;
  return cloneQuest(q);
}

export function cloneQuest(q: IQuest): IQuest {
  return {
    ...q,
    stages: q.stages.map(s => ({
      ...s,
      objectives: s.objectives.map(o => ({ ...o })),
      rewards: s.rewards ? s.rewards.map(r => ({ ...r })) : undefined,
    })),
    rewards: q.rewards.map(r => ({ ...r })),
  };
}