/** 随机抽取一条道侣剧情 */
export function pickDaoLuStory(excludeIds: string[] = []): IDaoLuStory {
  const available = DAOLU_STORY_LIBRARY.filter(s => !excludeIds.includes(s.id));
  const idx = Math.floor(Math.random() * available.length);
  return available[idx];
}

/** 随机抽取指定数量的道侣剧情 */
export function pickDaoLuStories(count: number, excludeIds: string[] = []): IDaoLuStory[] {
  const available = DAOLU_STORY_LIBRARY.filter(s => !excludeIds.includes(s.id));
  const pool = [...available];
  const picked: IDaoLuStory[] = [];
  for (let i = 0; i < count && pool.length > 0; i++) {
    const idx = Math.floor(Math.random() * pool.length);
    picked.push(pool.splice(idx, 1)[0]);
  }
  return picked;
}