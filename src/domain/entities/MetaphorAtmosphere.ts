/** 填充完整文本 */
export function buildFullText(scene: IMetaphorAtmosphereScene): string {
  const lines: string[] = [];
  lines.push(scene.prelude);
  lines.push('');
  lines.push(...scene.climax);
  lines.push('');
  lines.push(scene.closing);
  return lines.join('\n');
}

/** 初始化所有场景的fullText */
export function initializeMetaphorLibrary(): void {
  for (const scene of METAPHOR_ATMOSPHERE_LIBRARY) {
    scene.fullText = buildFullText(scene);
  }
}

/** 根据亲密度获取场景 */
export function getMetaphorScenesByIntimacy(
  intimacy: number,
  excludeIds: number[] = []
): IMetaphorAtmosphereScene[] {
  return METAPHOR_ATMOSPHERE_LIBRARY.filter(
    s => intimacy >= s.intimacyRange[0] && intimacy <= s.intimacyRange[1] && !excludeIds.includes(s.id)
  );
}

/** 随机抽取指定数量的场景 */
export function pickMetaphorScenes(
  intimacy: number,
  count: number = 1,
  excludeIds: number[] = []
): IMetaphorAtmosphereScene[] {
  const available = getMetaphorScenesByIntimacy(intimacy, excludeIds);
  const pool = [...available];
  const picked: IMetaphorAtmosphereScene[] = [];
  for (let i = 0; i < count && pool.length > 0; i++) {
    const idx = Math.floor(Math.random() * pool.length);
    picked.push(pool.splice(idx, 1)[0]);
  }
  return picked;
}

